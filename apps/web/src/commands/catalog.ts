export type CommandId = keyof typeof COMMANDS;

/** Narrows a string to a command id (for tests and tools that walk the catalog). */
export const isCommandId = (value: string): value is CommandId =>
  Object.prototype.hasOwnProperty.call(COMMANDS, value);

export function commandTitle(id: CommandId): string {
  return COMMANDS[id].title;
}
