// `pnpm ui:tokens`: generates CSS custom properties and typed constants from packages/ui/tokens/*.ts
// (design-system §2, PLAN-005 S1). test/tokens-generated.test.ts fails when the committed output is stale.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import {
  componentTokens,
  hiResTokens,
  reducedMotionTokens,
  themedComponentTokens,
} from '../tokens/component.js';
import { LABEL_HUES, THEMES, primitivesFor, type Theme } from '../tokens/primitives.js';
import { semanticColors } from '../tokens/semantic.js';

const HEADER = 'Generated by `pnpm ui:tokens` from packages/ui/tokens/*.ts. Do not edit by hand.';

export const OUTPUTS = {
  css: fileURLToPath(new URL('../src/styles/tokens.css', import.meta.url)),
  ts: fileURLToPath(new URL('../src/tokens.gen.ts', import.meta.url)),
};

/** Names declared by more than one layer, which would silently override each other in CSS. */
export function duplicateNames(layers: Readonly<Record<string, Iterable<string>>>): string[] {
  const owner = new Map<string, string>();
  const duplicates: string[] = [];
  for (const [layer, names] of Object.entries(layers)) {
    for (const name of names) {
      const first = owner.get(name);
      if (first === undefined) owner.set(name, layer);
      else duplicates.push(`--${name} (${first} and ${layer})`);
    }
  }
  return duplicates;
}

/** Fails on a primitive missing from one theme, a dangling reference, or a name defined twice. */
function validate(): void {
  const [first, ...rest] = THEMES.map((theme) => [theme, primitivesFor(theme)] as const);
  if (!first) return;
  for (const [theme, primitives] of rest) {
    const a = [...first[1].keys()].sort().join();
    const b = [...primitives.keys()].sort().join();
    if (a !== b) throw new Error(`Primitives differ between ${first[0]} and ${theme}`);
  }
  for (const theme of THEMES) {
    const primitives = primitivesFor(theme);
    for (const [name, refs] of Object.entries(semanticColors)) {
      if (!primitives.has(refs[theme])) {
        throw new Error(`--${name} (${theme}) refers to an unknown primitive --${refs[theme]}`);
      }
    }
  }
  const duplicates = duplicateNames({
    primitive: first[1].keys(),
    semantic: Object.keys(semanticColors),
    component: Object.keys(componentTokens),
    themed: Object.keys(themedComponentTokens),
  });
  if (duplicates.length > 0) throw new Error(`Defined twice: ${duplicates.join(', ')}`);
  for (const name of Object.keys(hiResTokens)) {
    if (!(name in componentTokens)) throw new Error(`2x override --${name} has no default`);
  }
  for (const name of Object.keys(reducedMotionTokens)) {
    if (!(name in componentTokens))
      throw new Error(`Reduced-motion override --${name} has no default`);
  }
}

function declarations(entries: Iterable<readonly [string, string]>): string {
  return [...entries].map(([name, value]) => `  --${name}: ${value};`).join('\n');
}

function themeBody(theme: Theme): string {
  return [
    `  color-scheme: ${theme};`,
    declarations(primitivesFor(theme)),
    declarations(
      Object.entries(semanticColors).map(([name, refs]) => [name, `var(--${refs[theme]})`]),
    ),
    declarations(Object.entries(themedComponentTokens).map(([name, v]) => [name, v[theme]])),
  ].join('\n');
}

export function renderCss(): string {
  return `/* ${HEADER} */

:root {
${declarations(Object.entries(componentTokens))}
}

/* Light is the default. A subtree can opt into either theme with data-theme (e.g. Storybook). */
:root,
[data-theme='light'] {
${themeBody('light')}
}

[data-theme='dark'] {
${themeBody('dark')}
}

/* Before the theme bootstrap runs (or with scripts disabled), follow the OS. */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme]) {
${themeBody('dark')}
  }
}

/* Hairlines are half a pixel on 2x screens and 1 px elsewhere (design-system §2.5). */
@media (min-resolution: 2dppx) {
  :root {
${declarations(Object.entries(hiResTokens))}
  }
}

/* Reduced motion: overlays keep their opacity fade but stop moving (design-system §2.6). */
@media (prefers-reduced-motion: reduce) {
  :root {
${declarations(Object.entries(reducedMotionTokens))}
  }
}
`;
}

const camel = (name: string): string =>
  name.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());

export function renderTs(): string {
  const names = [
    ...Object.keys(semanticColors),
    ...Object.keys(componentTokens),
    ...Object.keys(themedComponentTokens),
  ];
  return `// ${HEADER}

/** CSS custom properties components may use (semantic and component layers), as \`var()\` references. */
export const token = {
${names.map((name) => `  ${camel(name)}: 'var(--${name})',`).join('\n')}
} as const;

export type Token = keyof typeof token;

/** The 12-hue palette for labels, teams and projects (design-system §2.2). */
export const LABEL_HUES = [${LABEL_HUES.map((h) => `'${h}'`).join(', ')}] as const;

export type LabelHue = (typeof LABEL_HUES)[number];

/** Theme names, as set on \`<html data-theme>\`. */
export const THEMES = [${THEMES.map((t) => `'${t}'`).join(', ')}] as const;

export type Theme = (typeof THEMES)[number];
`;
}

async function pretty(source: string, filepath: string): Promise<string> {
  const config = await resolveConfig(filepath);
  return format(source, { ...config, filepath });
}

/** Rendered, Prettier-formatted output for each generated file. */
export async function render(): Promise<Record<keyof typeof OUTPUTS, string>> {
  validate();
  return {
    css: await pretty(renderCss(), OUTPUTS.css),
    ts: await pretty(renderTs(), OUTPUTS.ts),
  };
}

async function main(): Promise<void> {
  const output = await render();
  await writeFile(OUTPUTS.css, output.css);
  await writeFile(OUTPUTS.ts, output.ts);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await main();
}
